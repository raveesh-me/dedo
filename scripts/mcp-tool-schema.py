#!/usr/bin/env python3
"""Print the MCP specification's Tool definition and every definition it
references, as one JSON Schema document.

Usage: mcp-tool-schema.py <schema.json> <spec version>

The input is a schema.json from github.com/modelcontextprotocol/
modelcontextprotocol (schema/<version>/schema.json). The output is stable, so
two versions can be compared with diff, and mcpserver's tests validate the
served tools against it.
"""
import json
import sys


def refs(node):
    if isinstance(node, dict):
        ref = node.get("$ref", "")
        if ref.startswith("#/$defs/") or ref.startswith("#/definitions/"):
            yield ref.rsplit("/", 1)[1]
        for value in node.values():
            yield from refs(value)
    elif isinstance(node, list):
        for value in node:
            yield from refs(value)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    with open(sys.argv[1]) as f:
        schema = json.load(f)
    defs = schema.get("$defs") or schema.get("definitions")
    if not defs or "Tool" not in defs:
        sys.exit(f"{sys.argv[1]}: no Tool definition")
    keep, todo = {}, ["Tool"]
    while todo:
        name = todo.pop()
        if name in keep:
            continue
        keep[name] = defs[name]
        todo.extend(refs(defs[name]))
    out = {
        "$schema": schema.get("$schema", "http://json-schema.org/draft-07/schema#"),
        "$comment": f"Tool from the MCP specification {sys.argv[2]}, generated by scripts/mcp-tool-schema.py.",
        "$ref": "#/$defs/Tool",
        "$defs": keep,
    }
    text = json.dumps(out, indent=2, sort_keys=True)
    # Older schemas use #/definitions/; one form keeps diffs meaningful.
    print(text.replace('"#/definitions/', '"#/$defs/'))


if __name__ == "__main__":
    main()
