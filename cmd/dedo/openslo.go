// The indicators are counted on the metric the runtime records for every
// call (package telemetry), by the semantic conventions' attributes.
const (
	sloMetric       = "rpc.server.call.duration"
	sloMethodAttr   = "rpc.method"
	sloErrorAttr    = "error.type"
	sloSourceType   = "OpenTelemetry"
	sloAPIVersion   = "openslo/v1"
	sloServiceLabel = "dedo.service"
	sloMethodLabel  = "dedo.rpc.method"
	sloHeader       = "# Code generated by dedo slo. DO NOT EDIT.\n"
)

// sloOptions configure the documents.
type sloOptions struct {
	// DataSource names an OpenSLO DataSource every indicator reads from,
	// as metricSourceRef; without it, they name the type OpenTelemetry.
	DataSource string
}

// sloDoc is one OpenSLO object.
type sloDoc struct {
	APIVersion string  `yaml:"apiVersion"`
	Kind       string  `yaml:"kind"`
	Metadata   sloMeta `yaml:"metadata"`
	Spec       any     `yaml:"spec"`
}

type sloMeta struct {
	Name        string            `yaml:"name"`
	DisplayName string            `yaml:"displayName,omitempty"`
	Labels      map[string]string `yaml:"labels,omitempty"`
}

type sloServiceSpec struct {
	Description string `yaml:"description,omitempty"`
}

type sliSpec struct {
	Description string      `yaml:"description,omitempty"`
	RatioMetric ratioMetric `yaml:"ratioMetric"`
}

type ratioMetric struct {
	Counter bool         `yaml:"counter"`
	Good    metricSource `yaml:"good"`
	Total   metricSource `yaml:"total"`
}

type metricSource struct {
	MetricSource metricSourceSpec `yaml:"metricSource"`
}

type metricSourceSpec struct {
	MetricSourceRef string      `yaml:"metricSourceRef,omitempty"`
	Type            string      `yaml:"type,omitempty"`
	Spec            metricQuery `yaml:"spec"`
}

// metricQuery says which calls to count, in terms any backend that holds
// OpenTelemetry metrics can translate: the count of rpc.server.call.duration
// observations with these attributes, without those, at most so long.
type metricQuery struct {
	Metric           string              `yaml:"metric"`
	Aggregation      string              `yaml:"aggregation"`
	Attributes       map[string][]string `yaml:"attributes"`
	AbsentAttributes []string            `yaml:"absentAttributes,omitempty"`
	MaxValueSeconds  float64             `yaml:"maxValueSeconds,omitempty"`
}

type sloSpec struct {
	Description     string          `yaml:"description,omitempty"`
	Service         string          `yaml:"service"`
	IndicatorRef    string          `yaml:"indicatorRef"`
	TimeWindow      []timeWindow    `yaml:"timeWindow"`
	BudgetingMethod string          `yaml:"budgetingMethod"`
	Objectives      []sloObjective  `yaml:"objectives"`
	AlertPolicies   []alertPolicyID `yaml:"alertPolicies,omitempty"`
}

type timeWindow struct {
	Duration  string `yaml:"duration"`
	IsRolling bool   `yaml:"isRolling"`
}

type sloObjective struct {
	DisplayName string  `yaml:"displayName"`
	Target      float64 `yaml:"target"`
}

type alertPolicyID struct {
	AlertPolicyRef string `yaml:"alertPolicyRef"`
}

type alertPolicySpec struct {
	Description         string            `yaml:"description"`
	AlertWhenBreaching  bool              `yaml:"alertWhenBreaching"`
	AlertWhenResolved   bool              `yaml:"alertWhenResolved"`
	AlertWhenNoData     bool              `yaml:"alertWhenNoData"`
	Conditions          []alertCondition  `yaml:"conditions"`
	NotificationTargets []notificationRef `yaml:"notificationTargets"`
}

type alertCondition struct {
	Kind     string             `yaml:"kind"`
	Metadata sloMeta            `yaml:"metadata"`
	Spec     alertConditionSpec `yaml:"spec"`
}

type alertConditionSpec struct {
	Description string   `yaml:"description"`
	Severity    string   `yaml:"severity"`
	Condition   burnRate `yaml:"condition"`
}

type burnRate struct {
	Kind           string  `yaml:"kind"`
	Op             string  `yaml:"op"`
	Threshold      float64 `yaml:"threshold"`
	LookbackWindow string  `yaml:"lookbackWindow"`
	AlertAfter     string  `yaml:"alertAfter"`
}

type notificationRef struct {
	TargetRef string `yaml:"targetRef"`
}

// burnAlerts are the multiwindow burn-rate alerts of the SRE workbook: a
// page when a 30-day budget would be gone in about two days, a ticket when
// in five.
var burnAlerts = []struct {
	suffix, severity, lookback, after string
	threshold                         float64
}{
	{"fast-burn", "page", "1h", "5m", 14.4},
	{"slow-burn", "ticket", "6h", "30m", 6},
}

// sloGroup is a set of RPCs measured against one set of objectives.
type sloGroup struct {
	name       string // the base of its objects' names
	display    string
	method     string // the RPC, for an RPC's own objectives
	objectives *dedov1.Objectives
	all        []string // every RPC, for availability
	unary      []string // the RPCs whose duration is a call's, for latency
}

// openSLO returns the OpenSLO v1 documents of a service's objectives, or
// nil when it declares none.
func openSLO(svc protoreflect.ServiceDescriptor, opts sloOptions) ([]byte, error) {
	rules, _ := proto.GetExtension(svc.Options(), dedov1.E_Service).(*dedov1.ServiceRules)
	level := rules.GetServiceLevel()
	groups, err := sloGroups(svc, level)
	if err != nil || len(groups) == 0 {
		return nil, err
	}
	full := string(svc.FullName())
	base := sloName(full)
	labels := map[string]string{sloServiceLabel: full}
	docs := []sloDoc{{
		APIVersion: sloAPIVersion, Kind: "Service",
		Metadata: sloMeta{Name: base, DisplayName: displayName(full), Labels: labels},
		Spec:     sloServiceSpec{Description: fmt.Sprintf("%s, owned by %s.", full, rules.GetOwnerTeam())},
	}}
	docs = append(docs, alertPolicies(base, rules.GetOwnerTeam(), labels)...)
	window := timeWindow{Duration: fmt.Sprintf("%dd", int(level.GetWindow().AsDuration().Hours()/24)), IsRolling: true}
	for _, g := range groups {
		docs = append(docs, groupDocs(base, g, window, labels, opts)...)
	}
	return encodeSLO(docs)
}

// sloGroups splits the RPCs into the service's group and one group per RPC
// with objectives of its own, checking every declaration.
func sloGroups(svc protoreflect.ServiceDescriptor, level *dedov1.ServiceLevel) ([]sloGroup, error) {
	var problems []string
	for _, p := range objectives.ServiceProblems(level) {
		problems = append(problems, fmt.Sprintf("%s: %s", svc.FullName(), p))
	}
	service := sloGroup{name: "", display: string(svc.Name()), objectives: level.GetObjectives()}
	var own []sloGroup
	methods := svc.Methods()
	for i := range methods.Len() {
		m := methods.Get(i)
		rules, _ := proto.GetExtension(m.Options(), dedov1.E_Method).(*dedov1.MethodRules)
		streaming := m.IsStreamingClient() || m.IsStreamingServer()
		for _, p := range objectives.MethodProblems(rules.GetServiceLevel(), level, streaming) {
			problems = append(problems, fmt.Sprintf("%s: %s", m.FullName(), p))
		}
		method := fmt.Sprintf("%s/%s", svc.FullName(), m.Name())
		switch l := rules.GetServiceLevel().GetLevel().(type) {
		case *dedov1.MethodServiceLevel_Exempt:
			continue
		case *dedov1.MethodServiceLevel_Objectives:
			g := sloGroup{name: strings.ToLower(string(m.Name())), display: string(m.Name()), method: method, objectives: l.Objectives, all: []string{method}}
			if !streaming {
				g.unary = []string{method}
			}
			own = append(own, g)
			continue
		}
		service.all = append(service.all, method)
		if !streaming {
			service.unary = append(service.unary, method)
		}
	}
	if len(problems) > 0 {
		return nil, errors.New(strings.Join(problems, "\n"))
	}
	if level == nil {
		return own, nil
	}
	return append([]sloGroup{service}, own...), nil
}

// groupDocs are the SLIs and SLOs of one group's objectives.
func groupDocs(base string, g sloGroup, window timeWindow, labels map[string]string, opts sloOptions) []sloDoc {
	prefix := base
	if g.name != "" {
		prefix = base + "-" + g.name
	}
	if g.method != "" {
		labels = map[string]string{sloServiceLabel: labels[sloServiceLabel], sloMethodLabel: g.method}
	}
	var docs []sloDoc
	if a := g.objectives.GetAvailability(); a != 0 && len(g.all) > 0 {
		good := query(g.all)
		good.AbsentAttributes = []string{sloErrorAttr}
		docs = append(docs, pair(base, prefix+"-availability", g.display+" availability",
			"Calls that are not server errors: no error.type.", a, good, query(g.all), window, labels, opts)...)
	}
	for _, l := range g.objectives.GetLatency() {
		if len(g.unary) == 0 {
			continue
		}
		seconds := l.GetThreshold().AsDuration().Seconds()
		good := query(g.unary)
		good.MaxValueSeconds = seconds
		docs = append(docs, pair(base, fmt.Sprintf("%s-latency-%s", prefix, percentileName(l.GetPercentile())),
			fmt.Sprintf("%s %s latency", g.display, percentileName(l.GetPercentile())),
			fmt.Sprintf("Calls that answer within %gs.", seconds), l.GetPercentile(), good, query(g.unary), window, labels, opts)...)
	}
	return docs
}

// pair is an SLI and the SLO that targets it.
func pair(service, name, display, description string, target float64, good, total metricQuery, window timeWindow, labels map[string]string, opts sloOptions) []sloDoc {
	name = sloName(name)
	meta := sloMeta{Name: name, DisplayName: displayName(display), Labels: labels}
	var policies []alertPolicyID
	for _, a := range burnAlerts {
		policies = append(policies, alertPolicyID{AlertPolicyRef: sloName(service + "-" + a.suffix)})
	}
	return []sloDoc{
		{APIVersion: sloAPIVersion, Kind: "SLI", Metadata: meta, Spec: sliSpec{
			Description: description,
			RatioMetric: ratioMetric{Counter: true, Good: source(good, opts), Total: source(total, opts)},
		}},
		{APIVersion: sloAPIVersion, Kind: "SLO", Metadata: meta, Spec: sloSpec{
			Service: service, IndicatorRef: name, TimeWindow: []timeWindow{window}, BudgetingMethod: "Occurrences",
			Objectives:    []sloObjective{{DisplayName: display, Target: target}},
			AlertPolicies: policies,
		}},
	}
}

func query(methods []string) metricQuery {
	return metricQuery{Metric: sloMetric, Aggregation: "count", Attributes: map[string][]string{sloMethodAttr: methods}}
}

func source(q metricQuery, opts sloOptions) metricSource {
	if opts.DataSource != "" {
		return metricSource{MetricSource: metricSourceSpec{MetricSourceRef: sloName(opts.DataSource), Spec: q}}
	}
	return metricSource{MetricSource: metricSourceSpec{Type: sloSourceType, Spec: q}}
}

// alertPolicies are the service's burn-rate alerts, notifying its owner
// team: an AlertNotificationTarget the organisation defines by that name.
func alertPolicies(base, owner string, labels map[string]string) []sloDoc {
	var docs []sloDoc
	for _, a := range burnAlerts {
		name := sloName(base + "-" + a.suffix)
		docs = append(docs, sloDoc{
			APIVersion: sloAPIVersion, Kind: "AlertPolicy",
			Metadata: sloMeta{Name: name, Labels: labels},
			Spec: alertPolicySpec{
				Description:        fmt.Sprintf("The error budget burns %gx too fast over %s.", a.threshold, a.lookback),
				AlertWhenBreaching: true,
				Conditions: []alertCondition{{
					Kind:     "AlertCondition",
					Metadata: sloMeta{Name: name},
					Spec: alertConditionSpec{
						Description: fmt.Sprintf("Burn rate above %g over %s", a.threshold, a.lookback),
						Severity:    a.severity,
						Condition:   burnRate{Kind: "burnrate", Op: "gt", Threshold: a.threshold, LookbackWindow: a.lookback, AlertAfter: a.after},
					},
				}},
				NotificationTargets: []notificationRef{{TargetRef: sloName(owner)}},
			},
		})
	}
	return docs
}

func encodeSLO(docs []sloDoc) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString(sloHeader)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	for _, d := range docs {
		if err := enc.Encode(d); err != nil {
			return nil, fmt.Errorf("encoding %s %s: %w", d.Kind, d.Metadata.Name, err)
		}
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// percentileName names a percentile: p99 for 0.99, p99-9 for 0.999.
func percentileName(p float64) string {
	// Rounded to the hundredth of a percent, so 0.9999 is p99-99 and not
	// p99-99000000000001.
	percent := math.Round(p*10000) / 100
	return "p" + strings.ReplaceAll(strconv.FormatFloat(percent, 'f', -1, 64), ".", "-")
}

var notName = regexp.MustCompile(`[^a-z0-9]+`)

// sloName makes an OpenSLO object name, an RFC 1123 label: lowercase
// letters, digits and dashes, at most 63 characters. A longer name keeps
// its start and a hash of the whole.
func sloName(s string) string {
	name := strings.Trim(notName.ReplaceAllString(strings.ToLower(s), "-"), "-")
	if len(name) <= 63 {
		return name
	}
	sum := sha256.Sum256([]byte(s))
	return strings.TrimRight(name[:54], "-") + "-" + hex.EncodeToString(sum[:])[:8]
}

// displayName is s, or nothing when OpenSLO's 63 characters are too few.
func displayName(s string) string {
	if len(s) > 63 {
		return ""
	}
	return s
}
