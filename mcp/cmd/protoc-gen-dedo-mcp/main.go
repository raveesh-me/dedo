// Command protoc-gen-dedo-mcp writes the MCP tools of every service: one Go
// file per proto file, in the messages' package, with
//
//	// The JSON Schemas of each unary RPC's input and output (package schema).
//	var MCPInputSchemas = map[string]string{"pkg.Service.Method": `{...}`}
//	var MCPOutputSchemas = map[string]string{...}
//
//	// Each service's unary, non-deprecated RPCs as tools, for
//	// mcpserver.AddTools: the definitions written out, and forwarders that
//	// use the generated message types.
//	func CounterServiceMCPTools() []mcpserver.Tool
//
// so nothing about the tools is resolved by reflection while serving.
package main

import (
	"encoding/json"
	"fmt"
	"sort"
	"strconv"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/types/pluginpb"

	"github.com/raveesh-me/dedo/mcp/mcpserver"
	"github.com/raveesh-me/dedo/mcp/schema"
)

const (
	jsonPkg      = protogen.GoImportPath("encoding/json")
	mcpPkg       = protogen.GoImportPath("github.com/modelcontextprotocol/go-sdk/mcp")
	mcpserverPkg = protogen.GoImportPath("github.com/raveesh-me/dedo/mcp/mcpserver")
)

func main() {
	protogen.Options{}.Run(func(plugin *protogen.Plugin) error {
		plugin.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)
		for _, f := range plugin.Files {
			if f.Generate && len(f.Services) > 0 {
				if err := generate(plugin, f); err != nil {
					return err
				}
			}
		}
		return nil
	})
}

func generate(plugin *protogen.Plugin, f *protogen.File) error {
	inputs, outputs := map[string]string{}, map[string]string{}
	for _, svc := range f.Services {
		for _, m := range svc.Methods {
			if m.Desc.IsStreamingClient() || m.Desc.IsStreamingServer() {
				continue
			}
			in, err := json.Marshal(schema.Input(m))
			if err != nil {
				return err
			}
			out, err := json.Marshal(schema.Output(m))
			if err != nil {
				return err
			}
			inputs[string(m.Desc.FullName())] = string(in)
			outputs[string(m.Desc.FullName())] = string(out)
		}
	}
	if len(inputs) == 0 {
		return nil
	}
	g := plugin.NewGeneratedFile(f.GeneratedFilenamePrefix+".mcp.pb.go", f.GoImportPath)
	g.P("// Code generated by protoc-gen-dedo-mcp. DO NOT EDIT.")
	g.P("// source: ", f.Desc.Path())
	g.P()
	g.P("package ", f.GoPackageName)
	g.P()
	writeMap(g, "MCPInputSchemas", "MCP tool input, built from the request message, its field comments and\n// google.api.field_behavior.", inputs)
	g.P()
	writeMap(g, "MCPOutputSchemas", "MCP tool output: the response message as mcpserver encodes it in\n// structuredContent.", outputs)
	for _, svc := range f.Services {
		if err := writeTools(g, svc); err != nil {
			return err
		}
	}
	return nil
}

// writeTools writes <Service>MCPTools, with each tool's definition as
// mcpserver.Describe returns it and a typed forwarder.
func writeTools(g *protogen.GeneratedFile, svc *protogen.Service) error {
	var methods []*protogen.Method
	for _, m := range svc.Methods {
		if mcpserver.Serves(m.Desc) {
			methods = append(methods, m)
		}
	}
	if len(methods) == 0 {
		return nil
	}
	name := svc.GoName + "MCPTools"
	tool := g.QualifiedGoIdent(protogen.GoIdent{GoName: "Tool", GoImportPath: mcpserverPkg})
	g.P()
	g.P("// ", name, " returns ", svc.GoName, "'s unary, non-deprecated RPCs as MCP tools.")
	g.P("// Register them with mcpserver.AddTools.")
	g.P("func ", name, "() []", tool, " {")
	g.P("return []", tool, "{")
	for _, m := range methods {
		t, err := mcpserver.Describe(m.Desc)
		if err != nil {
			return err
		}
		full := strconv.Quote(string(m.Desc.FullName()))
		raw := g.QualifiedGoIdent(protogen.GoIdent{GoName: "RawMessage", GoImportPath: jsonPkg})
		g.P("{")
		g.P("Tool: &", g.QualifiedGoIdent(protogen.GoIdent{GoName: "Tool", GoImportPath: mcpPkg}), "{")
		g.P("Name: ", strconv.Quote(t.Name), ",")
		g.P("Title: ", strconv.Quote(t.Title), ",")
		g.P("Description: ", strconv.Quote(t.Description), ",")
		a := t.Annotations
		g.P("Annotations: &", g.QualifiedGoIdent(protogen.GoIdent{GoName: "ToolAnnotations", GoImportPath: mcpPkg}), "{")
		g.P("Title: ", strconv.Quote(a.Title), ",")
		g.P("ReadOnlyHint: ", a.ReadOnlyHint, ",")
		g.P("IdempotentHint: ", a.IdempotentHint, ",")
		boolean := g.QualifiedGoIdent(protogen.GoIdent{GoName: "Bool", GoImportPath: mcpserverPkg})
		if a.DestructiveHint != nil {
			g.P("DestructiveHint: ", boolean, "(", *a.DestructiveHint, "),")
		}
		if a.OpenWorldHint != nil {
			g.P("OpenWorldHint: ", boolean, "(", *a.OpenWorldHint, "),")
		}
		g.P("},")
		g.P("InputSchema: ", raw, "(MCPInputSchemas[", full, "]),")
		g.P("OutputSchema: ", raw, "(MCPOutputSchemas[", full, "]),")
		g.P("},")
		procedure := fmt.Sprintf("/%s/%s", svc.Desc.FullName(), m.Desc.Name())
		g.P("Call: ", g.QualifiedGoIdent(protogen.GoIdent{GoName: "Unary", GoImportPath: mcpserverPkg}),
			"[", g.QualifiedGoIdent(m.Input.GoIdent), ", ", g.QualifiedGoIdent(m.Output.GoIdent), "](", strconv.Quote(procedure), "),")
		g.P("},")
	}
	g.P("}")
	g.P("}")
	return nil
}

func writeMap(g *protogen.GeneratedFile, name, doc string, schemas map[string]string) {
	g.P("// ", name, " maps each unary RPC's full name to the JSON Schema of its")
	g.P("// ", doc)
	g.P("var ", name, " = map[string]string{")
	names := make([]string, 0, len(schemas))
	for n := range schemas {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		g.P(strconv.Quote(n), ": ", strconv.Quote(schemas[n]), ",")
	}
	g.P("}")
}
