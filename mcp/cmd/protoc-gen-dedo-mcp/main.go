// Command protoc-gen-dedo-mcp writes the MCP tool input schema of every
// unary RPC, built from its request message with field comments and
// google.api.field_behavior (see package schema). The output is one Go file
// per proto file, in the messages' package:
//
//	var MCPInputSchemas = map[string]string{"pkg.Service.Method": `{...}`}
//
// Pass it to mcpserver.New as Config.InputSchemas.
package main

import (
	"encoding/json"
	"sort"
	"strconv"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/types/pluginpb"

	"github.com/raveesh-me/dedo/mcp/schema"
)

func main() {
	protogen.Options{}.Run(func(plugin *protogen.Plugin) error {
		plugin.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)
		for _, f := range plugin.Files {
			if f.Generate && len(f.Services) > 0 {
				if err := generate(plugin, f); err != nil {
					return err
				}
			}
		}
		return nil
	})
}

func generate(plugin *protogen.Plugin, f *protogen.File) error {
	schemas := map[string]string{}
	for _, svc := range f.Services {
		for _, m := range svc.Methods {
			if m.Desc.IsStreamingClient() || m.Desc.IsStreamingServer() {
				continue
			}
			b, err := json.Marshal(schema.Input(m))
			if err != nil {
				return err
			}
			schemas[string(m.Desc.FullName())] = string(b)
		}
	}
	if len(schemas) == 0 {
		return nil
	}
	g := plugin.NewGeneratedFile(f.GeneratedFilenamePrefix+".mcp_schema.pb.go", f.GoImportPath)
	g.P("// Code generated by protoc-gen-dedo-mcp. DO NOT EDIT.")
	g.P("// source: ", f.Desc.Path())
	g.P()
	g.P("package ", f.GoPackageName)
	g.P()
	g.P("// MCPInputSchemas maps each unary RPC's full name to the JSON Schema of its")
	g.P("// MCP tool input, built from the request message, its field comments and")
	g.P("// google.api.field_behavior. Pass it to mcpserver.New.")
	g.P("var MCPInputSchemas = map[string]string{")
	names := make([]string, 0, len(schemas))
	for name := range schemas {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		g.P(strconv.Quote(name), ": ", strconv.Quote(schemas[name]), ",")
	}
	g.P("}")
	return nil
}
